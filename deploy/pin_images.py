#!/usr/bin/env python3
"""Resolve the exact images this repo deploys, and hand them to Helm and Compose.

`images.yaml` is the manifest: one file naming, by immutable digest, the image every
service runs. It exists because a tag cannot honestly carry that meaning. A tag
describes *one image's* content; `deploy/` needed something describing *the whole set*,
and overloading a single `image.tag` across eleven images only works while every image
changes on every commit. The moment one service changes and eight do not, the tag either
lies or has to be minted for images that did not earn it. A digest also cannot be moved,
which a tag can, so `git log deploy/images.yaml` is the deployment history and
`git revert` is the rollback.

What changed is how it reaches the two things that deploy. This script used to rewrite
`values.yaml` and `docker-compose.yml` in place with regular expressions, keep a third
generated file to undo the pinning for local builds, and run a `--check` mode hunting
for drift between the manifest and its own output. Both tools already accept this
natively:

* `images.yaml` **is** a Helm values file. `helm upgrade -f deploy/images.yaml` merges
  it over the chart's defaults. Nothing is rewritten, so `values.yaml` holds no digests
  and cannot disagree with the manifest.
* Compose substitutes variables from an env file. `docker-compose.yml` carries
  `image: <repo>${<SERVICE>_REF:-:latest}`, and this writes the `@sha256:...` values
  into `compose/images.env`.

So the only generated artifact left is that env file, and `--check` compares it against
the manifest rather than searching for drift in files people edit.

`base-image.digest` is deliberately separate. It is a *build* input -- which base a
service image is compiled FROM -- not something the chart deploys, and the chart's
values schema is strict, so it has no home in `images.yaml`.

    python deploy/pin_images.py                       # rewrite compose/images.env
    python deploy/pin_images.py --check               # fail if it is stale
    python deploy/pin_images.py --update a b --sha X  # resolve digests for a and b
"""

import argparse
import pathlib
import subprocess
import sys
from typing import Any

import yaml

ROOT = pathlib.Path(__file__).resolve().parent
MANIFEST = ROOT / "images.yaml"
BASE_DIGEST = ROOT / "base-image.digest"
COMPOSE_ENV = ROOT / "compose" / "images.env"

BASE = "base-serve"

MANIFEST_HEADER = """\
# The images this release deploys, by digest. Generated by deploy/pin_images.py; CI
# updates it on every push to main that rebuilds something.
#
# This is a Helm values file, consumed directly:
#
#     helm upgrade ai-residency ./helm/ai-residency -f ../images.yaml
#
# Omit the -f and the chart falls back to `image.tag`, which is what a local cluster
# wants: images built on this machine have their own digests and would never match one
# named here.
"""

ENV_HEADER = """\
# Generated by deploy/pin_images.py from images.yaml -- do not edit.
#
# Compose substitutes these into docker-compose.yml. Each value is the whole reference
# suffix, `@sha256:...`, so an unset variable falls back to `:latest` through
# ${<NAME>_REF:-:latest} rather than producing `repo@`, which is not a parseable
# reference at all.
#
#     docker compose --env-file images.env -f docker-compose.yml up -d
"""


def load() -> dict[str, str]:
    """The manifest as a flat mapping of service name to digest, base image included."""
    data: dict[str, Any] = yaml.safe_load(MANIFEST.read_text()) or {}
    images = {name: spec["digest"] for name, spec in (data.get("backends") or {}).items()}
    frontend = (data.get("frontend") or {}).get("digest")
    if frontend:
        images["frontend"] = frontend
    if BASE_DIGEST.exists():
        images[BASE] = BASE_DIGEST.read_text().strip()
    return images


def repo_for(name: str) -> str:
    """The Docker Hub repository for a service name."""
    if name in {BASE, "frontend"}:
        return f"roshb/ai-residency-{name}"
    return f"roshb/ai-residency-{name}-serve"


def env_var_for(name: str) -> str:
    """The Compose variable holding one service's reference suffix."""
    return name.upper().replace("-", "_") + "_REF"


def resolve(name: str, sha: str) -> str:
    """The digest the registry currently has for `name` at `sha-<commit>`.

    Only images CI actually rebuilt have that tag. Everything else keeps the digest
    already in the manifest, which is the point: an unchanged image needs no new tag,
    and the manifest is what carries "the set", so nothing has to be minted for it.
    """
    ref = f"{repo_for(name)}:sha-{sha}"
    out = subprocess.run(
        ["docker", "buildx", "imagetools", "inspect", ref, "--format", "{{.Manifest.Digest}}"],
        capture_output=True,
        text=True,
        timeout=180,
    )
    digest = out.stdout.strip()
    if not digest.startswith("sha256:"):
        raise SystemExit(f"could not resolve {ref}\n{out.stderr.strip()[:400]}")
    return digest


def write_manifest(images: dict[str, str]) -> None:
    """Rewrite `images.yaml` and `base-image.digest` from a flat mapping."""
    backends = {
        name: {"digest": digest}
        for name, digest in images.items()
        if name not in {BASE, "frontend"}
    }
    document: dict[str, Any] = {"backends": backends}
    if "frontend" in images:
        document["frontend"] = {"digest": images["frontend"]}
    MANIFEST.write_text(MANIFEST_HEADER + "\n" + yaml.safe_dump(document, sort_keys=False))
    if BASE in images:
        BASE_DIGEST.write_text(images[BASE] + "\n")


def update(names: list[str], sha: str) -> bool:
    """Point `names` at whatever the registry has for them at `sha`. True if changed."""
    images = load()
    changed = False
    for name in names:
        digest = resolve(name, sha)
        if images.get(name) != digest:
            print(f"{name:<30} {str(images.get(name))[:19]} -> {digest[:19]}")
            images[name] = digest
            changed = True
        else:
            print(f"{name:<30} unchanged")
    if changed:
        write_manifest(images)
    return changed


def render_env(images: dict[str, str]) -> str:
    """The Compose env file: one `<SERVICE>_REF=@sha256:...` line per deployed image."""
    lines = [ENV_HEADER]
    for name, digest in images.items():
        if name == BASE:
            continue
        lines.append(f"{env_var_for(name)}=@{digest}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail on drift instead of writing")
    parser.add_argument("--update", nargs="*", metavar="NAME", help="images to re-resolve")
    parser.add_argument("--sha", help="commit whose sha- tag holds the rebuilt images")
    args = parser.parse_args()

    if args.update is not None:
        if not args.sha:
            parser.error("--update needs --sha")
        if not args.update:
            print("nothing was rebuilt; the manifest already describes this commit")
        else:
            update(args.update, args.sha)

    images = load()
    if not images:
        print(f"{MANIFEST.name} names no images")
        return 1

    before = COMPOSE_ENV.read_text() if COMPOSE_ENV.exists() else ""
    after = render_env(images)
    if before == after:
        if args.check:
            print("compose/images.env matches images.yaml")
        return 0

    if args.check:
        print(f"{COMPOSE_ENV.relative_to(ROOT.parent)} is out of date with images.yaml")
        print("Run: python deploy/pin_images.py")
        return 1

    COMPOSE_ENV.write_text(after)
    print(f"updated {COMPOSE_ENV.relative_to(ROOT.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
